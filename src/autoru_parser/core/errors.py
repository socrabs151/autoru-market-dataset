"""Ошибки проекта.

Отдельные типы нужны, чтобы отличать «сайт не отдал данные» от «данных нет».
Это разные вещи: первое — сбой сбора, второе — результат.
"""

from __future__ import annotations


class ParserError(Exception):
    """Базовая ошибка парсера."""


class ParseError(ParserError):
    """Ответ получен, но разобрать его не удалось.

    Важный случай: сайт отдал страницу, а ожидаемого состояния в ней нет.
    Это сбой сбора, а не пустая выборка, и молчать о нём нельзя.
    """


class NoResults(ParserError):
    """Ответа по этому адресу не существует: сайт вернул 404.

    Это не сбой, а нормальный исход дробления. Часть фильтров при переборе
    значений всегда оказывается пустой — например, трёхдверный внедорожник у
    конкретной модели бывает только до определённого года.

    Ошибка отдельная именно поэтому: если считать 404 поломкой, обход
    останавливается на первом же пустом ответе, и полнота выборки теряется.
    """


class EmptyResultError(ParseError):
    """Состояние разобралось, но объявлений нет, хотя сайт их показывает.

    Признак того, что канал данных перестал работать: раньше на этой странице
    объявления были.
    """


class BlockedBySite(ParserError):
    """Сайт не отдал данные: капча, отказ или ограничение по частоте.

    Не считать это пустой выборкой. Здесь нужно ждать и повторять, а если
    капча — звать человека.
    """


class CaptchaRequired(BlockedBySite):
    """Требуется ручное прохождение проверки."""


class LimitReached(ParserError):
    """Исчерпан плановый лимит запросов."""


__all__ = [
    "BlockedBySite",
    "CaptchaRequired",
    "EmptyResultError",
    "LimitReached",
    "NoResults",
    "ParseError",
    "ParserError",
]
