"""Слой для проверок «человек».

auto.ru умеет попросить подтверждение запроса. В этот момент правильный ответ —
остановиться и позвать человека, а не искать способ обойти: обход защиты
не входит в проект ни в каком виде (решение 1).

Как это выглядит технически: обычный сбор доходит до состояния, где сайт
просит подтверждение, и завершается с понятным сообщением. Дальше человек
либо сам открывает нужную страницу в браузере и выполняет проверку, после
чего запускает сбор заново, либо заводит браузерную сессию и повторяет сбор
из неё. Автоматической передачи сессии здесь нет: она потребовала бы держать
браузер и разбирать его состояние, а выигрыш не перевешивает сложность.
"""

from __future__ import annotations

import structlog

from autoru_parser.core.errors import CaptchaRequired

log = structlog.get_logger(__name__)

MESSAGE = (
    "Сайт просит подтвердить запрос.\n\n"
    "Что делать:\n"
    "  1. Откройте нужную страницу auto.ru в обычном браузере.\n"
    "  2. Пройдите проверку вручную.\n"
    "  3. Запустите сбор снова — сессия браузера вам не нужна, парсер\n"
    "     работает без браузера и обычно обходится без проверки.\n\n"
    "Если проверка появляется каждый раз, скажите: возможно, темп слишком\n"
    "высок для этого адреса. Понизить его можно флагом --rps."
)


def explain() -> str:
    """Пояснение для человека. Текст одинаковый, чтобы не расходились."""
    return MESSAGE


def report(exc: CaptchaRequired) -> None:
    """Записать в лог факт запроса проверки."""
    log.warning("captcha.required", detail=str(exc), action="wait_for_human")


__all__ = ["MESSAGE", "explain", "report"]
